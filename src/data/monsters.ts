export const ALL_MONSTERS_LIST: MonsterDef[] = Object.values(MONSTERS_DB);
export const TOTAL_MONSTER_COUNT = ALL_MONSTERS_LIST.length; // 6 existing + 30 expansion = 36

export function getAreaForDay(day: number): AreaDef {
  let current = AREAS_DB[0];
  for (const area of AREAS_DB) {
    if (day >= area.minDay) current = area;
  }
  return current;
}

export function getAreaNamesLabel(areas: AreaId[]): string {
  return areas.map((id) => AREA_NAME_MAP[id]).join(" / ");
}

interface SpawnCandidate {
  id: string;
  weight: number;
}

export function pickEnemyIdForDay(
  day: number,
  lastSpawnedIds: string[],
  activeBossLikeCount: number
): string {
  const area = getAreaForDay(day);
  const candidates: SpawnCandidate[] = [];

  for (const m of ALL_MONSTERS_LIST) {
    if (m.id === "exp_monster_26") continue; // Mimic uses dedicated 50-day block rule
    if (m.isStageBoss) continue; // boss_mid / boss_100 only on day % 10 === 0
    if (day < m.minDay) continue;

    // Prioritize monsters native to current area; allow previous-area elites at lower weight in late game
    const inCurrentArea = m.areas.includes(area.id);
    if (!inCurrentArea) {
      // Allow cross-area carry-over only for high-day endless or adjacent toughness
      if (day < 51) continue;
      if (m.type === "通常" && day > 60) continue;
    }

    // Boss-class field monsters (Chimera / Dragon): cap at 1 active at once
    if (m.type === "ボス" && activeBossLikeCount >= 1) continue;

    let weight = 10;
    if (m.type === "通常") {
      // Early monsters gradually give way to mid/late monsters without disappearing overnight
      const age = day - m.minDay;
      weight = Math.max(4, 16 - Math.floor(age * 0.28));
      if (!inCurrentArea) weight = 3;
    } else if (m.type === "レア") {
      weight = Math.min(8, 3 + (day - m.minDay) * 0.25);
    } else if (m.type === "強敵") {
      weight = Math.min(11, 3.5 + (day - m.minDay) * 0.3);
      if (!inCurrentArea) weight = 3.5;
    } else if (m.type === "ボス") {
      weight = Math.min(2.8, 1.0 + (day - m.minDay) * 0.06);
    }

    // Anti-streak penalty so the exact same monster doesn't flood consecutively
    const recentCount = lastSpawnedIds.filter((id) => id === m.id).length;
    if (recentCount >= 2) {
      weight *= 0.2;
    } else if (recentCount === 1) {
      weight *= 0.55;
    }

    if (weight > 0) {
      candidates.push({ id: m.id, weight });
    }
  }

  if (candidates.length === 0) {
    return "slime";
  }

  let totalWeight = 0;
  for (const c of candidates) totalWeight += c.weight;
  let roll = Math.random() * totalWeight;
  for (const c of candidates) {
    roll -= c.weight;
    if (roll <= 0) return c.id;
  }
  return candidates[candidates.length - 1].id;
}
